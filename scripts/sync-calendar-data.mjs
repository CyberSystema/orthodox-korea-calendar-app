#!/usr/bin/env node
/**
 * Sync the app's bundled calendar seed from the SINGLE SOURCE OF TRUTH.
 *
 * The calendar JSON is authored in exactly one place: `public/data/` in the
 * orthodox-korea-calendar repo. That is what GitHub serves to the app at runtime and
 * what the website serves. The app additionally *bundles* a copy so a first launch
 * with no network still shows a calendar — this script regenerates that copy so it is
 * a derived artifact, never something you edit by hand.
 *
 *   npm run sync:calendar-data     regenerate the bundled seed (+ its index module)
 *   npm run check:calendar-data    fail if the seed has drifted from the source
 *
 * Source resolution: a sibling checkout of the webapp repo if present (fast, offline,
 * and exactly what you just edited), otherwise GitHub.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SEED_DIR = path.join(APP_ROOT, 'assets', 'webapp-source', 'data');
const GENERATED_MODULE = path.join(
  APP_ROOT,
  'src',
  'features',
  'calendar',
  'bundledCalendarData.generated.ts',
);
const LOCAL_CANONICAL = path.resolve(APP_ROOT, '..', 'orthodox-korea-calendar', 'public', 'data');
const GITHUB_CONTENTS =
  'https://api.github.com/repos/CyberSystema/orthodox-korea-calendar/contents/public/data';
const GITHUB_RAW =
  'https://raw.githubusercontent.com/CyberSystema/orthodox-korea-calendar/refs/heads/main/public/data/';

const DATA_FILE = /^(\d{4})_(en|kr)\.json$/;
const checkOnly = process.argv.includes('--check');

async function exists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function resolveCanonical() {
  if (await exists(LOCAL_CANONICAL)) {
    const names = (await fs.readdir(LOCAL_CANONICAL)).filter((n) => DATA_FILE.test(n));
    return {
      label: `local checkout ${path.relative(APP_ROOT, LOCAL_CANONICAL)}`,
      names,
      read: (n) => fs.readFile(path.join(LOCAL_CANONICAL, n), 'utf8'),
    };
  }

  const res = await fetch(GITHUB_CONTENTS);
  if (!res.ok) throw new Error(`GitHub listing failed: ${res.status} ${res.statusText}`);
  const items = await res.json();
  const names = items.filter((i) => i.type === 'file' && DATA_FILE.test(i.name)).map((i) => i.name);
  return {
    label: 'GitHub CyberSystema/orthodox-korea-calendar@main',
    names,
    read: async (n) => {
      const r = await fetch(`${GITHUB_RAW}${n}`);
      if (!r.ok) throw new Error(`download of ${n} failed: ${r.status}`);
      return r.text();
    },
  };
}

/** Bundle the current (and next) year when available; otherwise the newest year there is. */
function pickSeedYears(names) {
  const years = [...new Set(names.map((n) => Number(n.match(DATA_FILE)[1])))].sort((a, b) => a - b);
  const now = new Date().getFullYear();
  const wanted = years.filter((y) => y === now || y === now + 1);
  if (wanted.length > 0) return wanted;
  return years.length > 0 ? [years[years.length - 1]] : [];
}

function generatedModule(plan) {
  const entries = plan
    .map(
      ({ year, en, kr }) => `  ${year}: () => ({
    en: require('../../../assets/webapp-source/data/${en}'),
    kr: require('../../../assets/webapp-source/data/${kr}'),
  }),`,
    )
    .join('\n');

  return `// AUTO-GENERATED by scripts/sync-calendar-data.mjs — DO NOT EDIT BY HAND.
//
// Offline seed used only on a first launch with no network. The calendar JSON's single
// source of truth is public/data/ in the orthodox-korea-calendar repo — edit it there,
// then run \`npm run sync:calendar-data\`. \`npm run check:calendar-data\` fails on drift.

type BundledYear = { en: unknown; kr: unknown };

export const BUNDLED_CALENDAR_YEARS: Record<number, () => BundledYear> = {
${entries}
};
`;
}

async function main() {
  const canonical = await resolveCanonical();
  const seedYears = pickSeedYears(canonical.names);
  if (seedYears.length === 0) {
    throw new Error('No YYYY_(en|kr).json files found in the source of truth.');
  }

  // Build the plan: a year is seedable only if it has an English file; Korean falls
  // back to English (mirrors the runtime loader's behaviour).
  const plan = [];
  for (const year of seedYears) {
    const en = `${year}_en.json`;
    if (!canonical.names.includes(en)) continue;
    const kr = canonical.names.includes(`${year}_kr.json`) ? `${year}_kr.json` : en;
    plan.push({ year, en, kr });
  }
  if (plan.length === 0)
    throw new Error(`No English data for seed year(s) ${seedYears.join(', ')}.`);

  const wanted = new Map();
  for (const { en, kr } of plan) {
    for (const name of new Set([en, kr])) {
      if (!wanted.has(name)) wanted.set(name, await canonical.read(name));
    }
  }
  const moduleText = generatedModule(plan);

  const seedNames = (await exists(SEED_DIR))
    ? (await fs.readdir(SEED_DIR)).filter((n) => DATA_FILE.test(n))
    : [];
  const extras = seedNames.filter((n) => !wanted.has(n));

  console.log(`Source of truth : ${canonical.label}`);
  console.log(`Seed year(s)    : ${plan.map((p) => p.year).join(', ')}`);

  if (checkOnly) {
    const drift = [];
    for (const [name, text] of wanted) {
      const p = path.join(SEED_DIR, name);
      const have = (await exists(p)) ? await fs.readFile(p, 'utf8') : null;
      if (have === null) drift.push(`${name} (missing from the bundled seed)`);
      else if (have !== text) drift.push(`${name} (differs from the source)`);
    }
    for (const extra of extras) drift.push(`${extra} (stale — not part of the seed)`);
    const haveModule = (await exists(GENERATED_MODULE))
      ? await fs.readFile(GENERATED_MODULE, 'utf8')
      : null;
    if (haveModule !== moduleText) drift.push('bundledCalendarData.generated.ts (out of date)');

    if (drift.length > 0) {
      console.error('\n✗ Bundled calendar seed has drifted from the source of truth:');
      for (const d of drift) console.error(`   - ${d}`);
      console.error('\n  Fix with:  npm run sync:calendar-data\n');
      process.exit(1);
    }
    console.log('✓ Bundled calendar seed matches the source of truth.');
    return;
  }

  await fs.mkdir(SEED_DIR, { recursive: true });
  let written = 0;
  for (const [name, text] of wanted) {
    const p = path.join(SEED_DIR, name);
    const have = (await exists(p)) ? await fs.readFile(p, 'utf8') : null;
    if (have !== text) {
      await fs.writeFile(p, text);
      console.log(`  updated ${name}`);
      written++;
    }
  }
  for (const extra of extras) {
    await fs.rm(path.join(SEED_DIR, extra));
    console.log(`  removed stale ${extra}`);
    written++;
  }
  const haveModule = (await exists(GENERATED_MODULE))
    ? await fs.readFile(GENERATED_MODULE, 'utf8')
    : null;
  if (haveModule !== moduleText) {
    await fs.writeFile(GENERATED_MODULE, moduleText);
    console.log('  updated bundledCalendarData.generated.ts');
    written++;
  }

  console.log(written === 0 ? '✓ Already up to date.' : `✓ Seed regenerated (${written} file(s)).`);
}

main().catch((err) => {
  console.error(`\n✗ ${err.message}\n`);
  process.exit(1);
});
